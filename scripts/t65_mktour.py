"""T6.5: write scripts/t65-tour.script, the screen tour that compares a build with FTN1.

    venv/bin/python scripts/t65_mktour.py [1|2|3]     (default 3)

From the warm 800M snapshot (main screen, track 1), the same keys on every build. On each
parameter page: a screen, then each encoder A..H one detent clockwise with a screen after each
(the header shows "Name=value": the long name and the formatter come from the descriptor table),
then each back one detent. Pages: TRIG, SYN, FLTR, AMP, FX, MOD (each key's pages, stepped with
DOWN), the three SEND FX pages (FUNC+FX, DOWN), the five MIXER pages (FUNC+MOD, DOWN); then the
LFO 1 destination list stepped through (encoder D), an encoder push on the flanger page's empty
knobs E and F (TEST in GT1T), and FUNC+FLTR (kit SETUP) and FUNC+AMP (Euclidean) as they open.
Screens are named NN-page-what so that scripts/t65_compare.py can pair them across builds.
The emulator delivers key taps in wall-clock time, so a screen taken a fixed emulated time after a
turn lands a little earlier or later from run to run; a knob shows its value for a moment after a
turn, then its label again. Version 1 (t65-tour.script) waits 0.35 s after a turn and 0.25 s between
the turns back; version 2 (t65-tour2.script) 0.6 s, which falls right on the value-to-label change;
version 3 (t65-tour3.script) takes each turn's screen 0.3 s after it (value shown) and the page's
last screen 3 s after the turns back (labels back), away from that change.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
import sys
VERSION = sys.argv[1] if len(sys.argv) > 1 else '3'
OUT = os.path.join(HERE, 't65-tour%s.script' % ('' if VERSION == '1' else VERSION))
# (wait after a turn before its screen, wait between the turns back, wait before the page's last screen)
WAITS = {'1': (0.35, 0.25, 0.3), '2': (0.6, 0.6, 2.5), '3': (0.3, 0.5, 3.0)}[VERSION]
L = ['# SPDX-License-Identifier: GPL-2.0-or-later',
     '# T6.5: screen tour for the table-growth builds (generated by scripts/t65_mktour.py; do not edit).',
     'wait-emu 0.5']
n = [0]


def png(what):
    L.append('png %03d-%s' % (n[0], what))
    n[0] += 1


def tap(k, wait=0.4, note=None):
    L.append('tap %s%s' % (k, ('                # ' + note) if note else ''))
    L.append('wait-emu %.1f' % wait)


def func(k, note):
    L.extend(['down space', 'wait-emu 0.1', 'tap %s                # FUNC+%s' % (k, note), 'wait-emu 0.1',
          'up space', 'wait-emu 0.5'])


def knobs(page):
    png(page)
    for i in range(1, 9):
        tap(str(i), WAITS[0])
        png('%s-%s+' % (page, 'ABCDEFGH'[i - 1]))
    for i in range(1, 9):
        tap('shift+%d' % i, WAITS[1])
    L.append('wait-emu %.1f' % WAITS[2])    # value popups gone, labels back
    png('%s-back' % page)


png('main')
for key, name, pages in (('o', 'trig', 2), ('p', 'syn', 3), ('bracketleft', 'fltr', 2),
                         ('bracketright', 'amp', 1), ('l', 'fx', 1), ('semicolon', 'mod', 3)):
    tap(key, 0.5, name.upper())
    for pg in range(pages):
        if pg:
            tap('Down', 0.5)
        knobs('%s%d' % (name, pg + 1))
func('l', 'FX: SEND FX 1')
knobs('send1')
tap('Down', 0.5)
knobs('send2')
tap('Down', 0.5)
knobs('send3')
for k in (5, 6):
    L += ['down F%d' % k, 'wait-emu 0.4']
    png('send3-push%s' % 'ABCDEFGH'[k - 1])
    L += ['up F%d' % k, 'wait-emu 0.3']
func('semicolon', 'MOD: MIXER')
for pg in range(5):
    if pg:
        tap('Down', 0.5)
    knobs('mixer%d' % (pg + 1))
tap('semicolon', 0.5, 'MOD: LFO 1')
png('lfo1')
for i in range(40):
    tap('4', 0.3 if VERSION == '1' else 0.5)
    if i % 4 == 3:
        png('lfo1-dest%02d' % (i + 1))
tap('BackSpace', 0.5, 'NO: leave the list')
png('lfo1-after')
func('bracketleft', 'FLTR: kit SETUP')
png('setup')
tap('BackSpace', 0.5)
func('bracketright', 'AMP: Euclidean')
png('eucl')
tap('BackSpace', 0.5)
tap('p', 0.5)
png('end')
with open(OUT, 'w') as f:
    f.write('\n'.join(L) + '\n')
print('%s: %d screens' % (OUT, n[0]))
