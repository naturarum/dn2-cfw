"""T5.3: write the key scripts that test the Echo page (SE01's main OS) in digikit's emulator.

    venv/bin/python scripts/t53_mkscripts.py

All start from a build's warm 800M snapshot (main screen, pattern A01, track 1, sequencer stopped)
and are run on SE1M and on GT01 with the same keys (scripts/t53-emu.sh run NAME SCRIPT):

  t53-echo.script        FUNC+FX (SEND FX 1): the page; each knob one detent up and back, MODE swept
                         up 0 -> 6 (one more: stays 6) and down to 0, AGE up 21 detents; MODE left at 3
  t53-frame-modeV.script V = 0..6: MODE turned down to 0, then up to V; AGE up 3 V detents; the end
                         snapshot's frame (scripts/t53_frame.py) must carry them at 0xa0a / 0xa18
  t53-kit.script         MODE 6, AGE up 10 on A01's kit; pattern A02 (its own kit), then A01 again:
                         the stored kit is loaded back through the stock pattern change
  t53-plock.script       grid recording, trig 1 held: FLTR A (a lockable sound knob: the control),
                         then on the Echo page TIME, MODE, AGE and REV turned with the trig held
  t53-band.script        the filter picture over E and F: BW 96, 64, 32, 0 at CNTR 32; CNTR 64, 96
                         at BW 0; BW 127 (no filter) and 119
  t53-midi-cc.script     CC 22 (MODE's, the X row's) on the FX channel (9, status b8) with 3, 6, 7,
                         127, 0, 1, then NRPN 257 = 5
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
HEAD = ['# SPDX-License-Identifier: GPL-2.0-or-later',
        '# T5.3 (generated by scripts/t53_mkscripts.py; do not edit).']


class S:
    def __init__(self, name, what):
        self.name, self.L, self.n = name, HEAD + ['# ' + what, 'wait-emu 0.5'], 0

    def png(self, what):
        self.L.append('png %02d-%s' % (self.n, what))
        self.n += 1

    def tap(self, k, wait=0.4, note=None):
        self.L.append('tap %s%s' % (k, ('                # ' + note) if note else ''))
        self.L.append('wait-emu %.1f' % wait)

    def func(self, k, note):
        self.L.extend(['down space', 'wait-emu 0.1', 'tap %s                # FUNC+%s' % (k, note),
                       'wait-emu 0.1', 'up space', 'wait-emu 0.8'])

    def wait(self, s):
        self.L.append('wait-emu %.1f' % s)

    def raw(self, *lines):
        self.L.extend(lines)

    def write(self):
        p = os.path.join(HERE, self.name + '.script')
        with open(p, 'w') as f:
            f.write('\n'.join(self.L) + '\n')
        print('%s: %d screens' % (p, self.n))


# ---- the page, every knob
s = S('t53-echo', 'the Echo page (SEND FX 1): each knob up and back, MODE swept, AGE up 21')
s.png('main')
s.func('l', 'FX: SEND FX 1')
s.png('echo')
for i, nm in ((1, 'A-time'),):
    s.tap(str(i), 0.3)
    s.png(nm + '+')
    s.tap('shift+%d' % i, 0.5)
for v in range(1, 8):
    s.tap('2', 0.4)
    s.png('B-mode-up%d' % v)
s.wait(3.0)
s.png('B-mode-label')
for v in range(1, 8):
    s.tap('shift+2', 0.4)
    s.png('B-mode-down%d' % v)
for i, nm in ((3, 'C-wid'), (4, 'D-fdbk'), (5, 'E-cntr'), (6, 'F-bw')):
    s.tap(str(i), 0.3)
    s.png(nm + '+')
    s.tap('shift+%d' % i, 0.5)
s.tap('7', 0.3)
s.png('G-age+1')
for _ in range(20):
    s.tap('7', 0.3)
s.png('G-age+21')
s.tap('8', 0.3)
s.png('H-rev+')
s.tap('shift+8', 0.5)
for _ in range(3):
    s.tap('2', 0.4)
s.png('B-mode3')
s.wait(3.0)
s.png('echo-end')
s.write()

# ---- one MODE value (and an AGE value) per run, for the frame
for v in range(7):
    s = S('t53-frame-mode%d' % v, 'MODE set to %d (down to 0 first) and AGE up %d detents, then the frame'
          % (v, 3 * v))
    s.func('l', 'FX: SEND FX 1')
    for _ in range(2):
        s.tap('shift+2', 0.4)
    for _ in range(v):
        s.tap('2', 0.4)
    for _ in range(3 * v):
        s.tap('7', 0.3)
    s.wait(2.0)
    s.png('echo')
    s.write()

# ---- the kit: set on A01, pattern A02, back to A01
s = S('t53-kit', 'MODE 6 and AGE +10 on A01, then pattern A02 (its own kit) and A01 again')
s.func('l', 'FX: SEND FX 1')
s.png('a01-echo')
for _ in range(6):
    s.tap('2', 0.4)
for _ in range(10):
    s.tap('7', 0.3)
s.wait(3.0)
s.png('a01-set')
for pat, key in (('a02', 'w'), ('a01', 'q')):
    s.tap('comma', 0.5, 'PTN')
    s.png('ptn-' + pat)
    s.tap(key, 0.8, 'pattern ' + pat.upper() + ' (the view stays on the Echo page)')
    s.wait(3.0)
    s.png(pat + '-echo')
s.write()

# ---- p-locks
s = S('t53-plock', 'grid recording, trig 1 held: FLTR A (control), then TIME, MODE, AGE, REV on the Echo page')
s.tap('0', 0.3, 'RECORD: grid recording on')
s.tap('q', 0.3, 'a trig on step 1')
s.png('grid')
s.tap('bracketleft', 0.5, 'FLTR')
s.raw('down q', 'wait-emu 0.3')
s.tap('1', 0.3)
s.png('fltr-a-held')
s.raw('up q', 'wait-emu 0.4')
s.func('l', 'FX: SEND FX 1')
s.png('echo')
s.raw('down q', 'wait-emu 0.3')
for k, nm in (('1', 'time'), ('2', 'mode'), ('7', 'age'), ('8', 'rev')):
    s.tap(k, 0.3)
    s.png(nm + '-held')
s.raw('up q', 'wait-emu 0.5')
s.png('released')
s.tap('2', 0.4)
s.png('mode-free')
s.tap('7', 0.4)
s.png('age-free')
s.tap('0', 0.3, 'RECORD off')
s.wait(2.0)
s.png('end')
s.write()

# ---- the band picture over E and F
s = S('t53-band', 'the filter picture: BW 96 -> 64 -> 32 -> 0, CNTR 32 -> 64 -> 96, BW -> 127, 119')
s.func('l', 'FX: SEND FX 1')
s.wait(2.0)
s.png('c32-b96')
for b in (64, 32, 0):
    for _ in range(32):
        s.tap('shift+6', 0.25)
    s.wait(2.0)
    s.png('c32-b%d' % b)
for c in (64, 96):
    for _ in range(32):
        s.tap('5', 0.25)
    s.wait(2.0)
    s.png('c%d-b0' % c)
for _ in range(130):
    s.tap('6', 0.25)
s.wait(2.0)
s.png('c96-b127')
for _ in range(8):
    s.tap('shift+6', 0.25)
s.wait(2.0)
s.png('c96-b119')
s.write()

# ---- MIDI CC and NRPN in for MODE
s = S('t53-midi-cc', 'CC 22 (MODE, the X row) and NRPN 257 on the FX channel 9 (b8)')
s.func('l', 'FX: SEND FX 1')
s.png('echo')
for v in (3, 6, 7, 127, 0, 1):
    s.raw('midi-in b8 16 %02x' % v, 'wait-emu 0.6')
    s.png('cc22-%d' % v)
s.raw('midi-in b8 63 02', 'wait-emu 0.05', 'midi-in b8 62 01', 'wait-emu 0.05',
      'midi-in b8 06 05', 'wait-emu 0.05', 'midi-in b8 26 00', 'wait-emu 0.6')
s.png('nrpn257-5')
s.wait(3.0)
s.png('end')
s.write()
