"""T6.5: write scripts/t65-midi-flood.script: every CC on every channel, then every NRPN (0..398,
and 399..420 past the map's end) on the track 1 channel (1), the FX channel (9) and channel 16.

    venv/bin/python scripts/t65_mkflood.py

Values are a fixed function of (channel, number), so two builds receive exactly the same bytes.
A short wait every 16 messages lets the MIDI task and the ParameterUpdateCache's flush run while
the flood goes on. Run with scripts/t65_live.py --cache-watch --flush-trace --state.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 't65-midi-flood.script')
L = ['# SPDX-License-Identifier: GPL-2.0-or-later',
     '# T6.5: MIDI CC and NRPN flood (generated by scripts/t65_mkflood.py; do not edit).',
     'wait-emu 0.5', 'png 00-before']
n = 0


def msg(*b):
    global n
    L.append('midi-in ' + ' '.join('%02x' % x for x in b))
    n += 1
    if n % 16 == 0:
        L.append('wait-emu 0.05')


for ch in range(16):
    for cc in range(128):
        msg(0xb0 | ch, cc, (cc * 7 + ch * 3 + 1) % 128)
L += ['wait-emu 0.5', 'png 01-after-cc']
for ch in (0, 8, 15):
    for nr in list(range(0, 399)) + list(range(399, 421)):
        msg(0xb0 | ch, 99, nr >> 7)
        msg(0xb0 | ch, 98, nr & 0x7f)
        msg(0xb0 | ch, 6, (nr * 5 + ch) % 128)
        msg(0xb0 | ch, 38, 0)
L += ['wait-emu 1.0', 'png 02-after-nrpn']
with open(OUT, 'w') as f:
    f.write('\n'.join(L) + '\n')
print('%s: %d messages' % (OUT, n))
