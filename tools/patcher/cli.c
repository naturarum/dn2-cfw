/*
 * cli.c - digiwerk-patch, the Terminal tool: a thin wrapper around the core (dn2patch.h), for macOS today and Linux or
 * Windows later.
 *
 *   ./digiwerk-patch                             asks which build (when it carries more than one), then for the file
 *   ./digiwerk-patch Digitone_II_OS1.12_dist.zip the same, with the file named here
 *   ./digiwerk-patch --pack FL01 FILE            picks the build without asking
 *   ./digiwerk-patch --list                      lists the builds it carries
 *
 * Its packs are compiled in (packs.h, made by mkpatch.py --embed), so it is one file to download. The input may be
 * Elektron's .zip itself (read with /usr/bin/unzip -p; not on Windows), the folder it unzips to, or the .syx. It
 * writes ID.syx next to it (ID: the build, e.g. OB01), only when the core hands it over (its sha256 is the one of
 * the build we tested), and never replaces an existing file without asking.
 */
#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#ifdef _WIN32
#include <io.h>
#define isatty _isatty
#define fileno _fileno
#else
#include <fcntl.h>
#include <signal.h>
#include <sys/wait.h>
#include <unistd.h>
#endif

#include "dn2patch.h"
#include "packs.h"                  /* packs[], pack_len[], NPACKS: generated by mkpatch.py --embed */

static int interactive;
static dn2p_info info[NPACKS];

/* A path as Terminal pastes it when a file is dropped on its window: special characters escaped with a backslash,
 * or the whole path in quotes, and a trailing space. -> the plain path, in place; a leading ~/ is the home folder. */
static void unshell(char *s, size_t cap)
{
    char *o = s, *i = s, q = 0;
    while (*i == ' ' || *i == '\t')
        i++;
    for (; *i; i++) {
        if (q) {
            if (*i == q)
                q = 0;
            else if (*i == '\\' && q == '"' && i[1])
                *o++ = *++i;
            else
                *o++ = *i;
        } else if (*i == '\'' || *i == '"')
            q = *i;
        else if (*i == '\\' && i[1])
            *o++ = *++i;
        else if (*i == ' ' || *i == '\t' || *i == '\n' || *i == '\r')
            break;
        else
            *o++ = *i;
    }
    *o = 0;
    const char *home = getenv("HOME");
    if (s[0] == '~' && s[1] == '/' && home && strlen(home) + strlen(s) < cap) {
        memmove(s + strlen(home), s + 1, strlen(s));
        memcpy(s, home, strlen(home));
    }
}

static int is_dir(const char *p)
{
    struct stat st;
    return !stat(p, &st) && (st.st_mode & S_IFMT) == S_IFDIR;
}

static int exists(const char *p)
{
    struct stat st;
    return !stat(p, &st);
}

static uint8_t *read_all(FILE *f, size_t *n)          /* a whole stream (at most DN2P_MAX_IN bytes and a bit) */
{
    uint8_t *p = NULL, *q;
    size_t cap = 0, k;
    *n = 0;
    do {
        if (*n == cap) {
            cap = cap ? 2 * cap : 1 << 20;
            if (!(q = realloc(p, cap))) {
                free(p);
                return NULL;
            }
            p = q;
        }
        k = fread(p + *n, 1, cap - *n, f);
        *n += k;
    } while (k && *n <= DN2P_MAX_IN);
    return p;
}

static uint8_t *slurp(const char *path, size_t *n)
{
    FILE *f = fopen(path, "rb");
    if (!f)
        return NULL;
    uint8_t *p = read_all(f, n);
    fclose(f);
    return p;
}

#ifndef _WIN32
/* The stock file inside Elektron's .zip: /usr/bin/unzip -p, run without a shell (so any path works). -> its bytes,
 * or NULL (no unzip, not a zip, or no Digitone_II_OS1.12.syx in it). */
static uint8_t *unzip_stock(const char *zip, size_t *n)
{
    char arg[4100];
    int fd[2];
    snprintf(arg, sizeof arg, "%s%s", zip[0] == '-' ? "./" : "", zip);
    if (pipe(fd))
        return NULL;
    pid_t pid = fork();
    if (pid == 0) {
        int nul = open("/dev/null", O_WRONLY);
        dup2(fd[1], 1);
        if (nul >= 0)
            dup2(nul, 2);
        close(fd[0]);
        close(fd[1]);
        execl("/usr/bin/unzip", "unzip", "-p", arg, "*" DN2P_STOCK_NAME, (char *)NULL);
        _exit(127);
    }
    close(fd[1]);
    if (pid < 0) {
        close(fd[0]);
        return NULL;
    }
    FILE *f = fdopen(fd[0], "rb");
    uint8_t *p = f ? read_all(f, n) : NULL;
    if (f)
        fclose(f);
    else
        close(fd[0]);
    int st;
    if (!p || *n > DN2P_MAX_IN)
        kill(pid, SIGKILL);
    waitpid(pid, &st, 0);
    if (!p || !WIFEXITED(st) || WEXITSTATUS(st) || *n == 0 || *n > DN2P_MAX_IN) {
        free(p);
        return NULL;
    }
    return p;
}
#endif

static int ask_yes(const char *q)
{
    char line[64];
    printf("%s (y/n) ", q);
    fflush(stdout);
    return fgets(line, sizeof line, stdin) && (line[0] == 'y' || line[0] == 'Y');
}

/* One try with one path and pack k: 0 done, 1 refused (another file may work), 2 failed (stop). */
static int run(char *path, int k)
{
    const char *name = info[k].id;
    char out[4200], tmp[4300], msg[DN2P_MSG];
    if (is_dir(path) && strlen(path) + sizeof DN2P_STOCK_NAME + 1 < 4096) {   /* the unzipped folder: the file in it */
        strcat(path, "/" DN2P_STOCK_NAME);
        if (!exists(path)) {
            printf("That folder has no " DN2P_STOCK_NAME " in it.\n");
            return 1;
        }
    }
    size_t n, outn;
    uint8_t *raw = slurp(path, &n), *o;
    if (!raw) {
        printf("I can't open that file: %s\n(%s)\n", path, strerror(errno));
        return 1;
    }
#ifndef _WIN32
    if (n >= 4 && !memcmp(raw, "PK\3\4", 4)) {     /* Elektron's .zip: the file inside, the output next to the .zip */
        free(raw);
        if (!(raw = unzip_stock(path, &n))) {
            printf("I couldn't find " DN2P_STOCK_NAME " in that .zip. Double-click the .zip in Finder to unzip it,\n"
                   "then use the " DN2P_STOCK_NAME " file inside.\n");
            return 1;
        }
    }
#endif
    int st = dn2patch_run(packs[k], pack_len[k], raw, n, NULL, NULL, &o, &outn, msg, sizeof msg);
    free(raw);
    char *detail = strchr(msg, '\n');
    if (detail)
        *detail++ = 0;
    printf("%s\n", msg);
    if (detail)
        printf("(details: %s)\n", detail);
    if (st != DN2P_OK)
        return st == DN2P_NOT_STOCK ? 1 : 2;
    /* the output goes next to the input */
    const char *slash = strrchr(path, '/');
#ifdef _WIN32
    const char *bs = strrchr(path, '\\');
    if (bs && (!slash || bs > slash))
        slash = bs;
#endif
    int dl = slash ? (int)(slash - path + 1) : 0;
    snprintf(out, sizeof out, "%.*s%s.syx", dl, path, name);
    if (exists(out)) {
        size_t en;
        uint8_t *e = slurp(out, &en);
        int same = e && dn2patch_is_build(packs[k], pack_len[k], e, en);
        free(e);
        if (same) {
            printf("%s is already there, and it is the right file. Nothing to do.\n", out);
            dn2patch_free(o);
            return 0;
        }
        printf("There is already a file called %s.syx in that folder.\n", name);
        if (!interactive || !ask_yes("Replace it?")) {
            printf("I left it alone. Move or rename it, then run me again.\n");
            dn2patch_free(o);
            return 2;
        }
    }
    snprintf(tmp, sizeof tmp, "%s.part", out);
    FILE *f = fopen(tmp, "wb");
    int ok = f && fwrite(o, 1, outn, f) == outn;
    ok = (f && !fclose(f)) && ok;
    dn2patch_free(o);
#ifdef _WIN32
    if (ok)
        remove(out);
#endif
    if (!ok || rename(tmp, out)) {
        printf("I couldn't write %s (%s).\n"
               "Copy " DN2P_STOCK_NAME " to your Desktop and use that copy instead.\n", out, strerror(errno));
        remove(tmp);
        return 2;
    }
    printf("\nDone. Wrote %s\n"
           "Send it to your Digitone II with Elektron Transfer, like an OS update from Elektron.\n", out);
    return 0;
}

/* a pack's effects or base features, by name: "3-band compressor, flanger" (mkpatch.py's EFFECTS and BASE) */
static void names(const char *ids, char *out, size_t n)
{
    static const char *names[][2] = { { "cmp3", "3-band compressor" }, { "flng", "flanger" },
                                      { "tape", "tape echo" }, { "spng", "spring reverb" },
                                      { "djvu", "D\u00e9j\u00e0 vu LFO" }, { "overbridge", "Overbridge works" } };
    char id[16];
    int at = 0;
    out[0] = 0;
    for (const char *p = ids; sscanf(p, "%15s", id) == 1; p = strchr(p, ' ') ? strchr(p, ' ') + 1 : p + strlen(p)) {
        const char *name = id;
        for (size_t i = 0; i < sizeof names / sizeof names[0]; i++)
            if (!strcmp(id, names[i][0]))
                name = names[i][1];
        at += snprintf(out + at, n - at, "%s%s", at ? ", " : "", name);
        if ((size_t)at >= n)
            break;
    }
}

static void list(void)
{
    char fx[128], base[128];
    for (int k = 0; k < NPACKS; k++) {
        names(info[k].effects, fx, sizeof fx);
        names(info[k].base, base, sizeof base);
        printf("  %d. %s \u00b7 %s\n     %s\n", k + 1, info[k].id, info[k].title, info[k].description);
        if (fx[0])
            printf("     effects: %s\n", fx);
        printf("     base: %s\n", base[0] ? base : "none");
        printf("     %s\n", info[k].record);
    }
}

/* which pack: --pack ID, the only one, or the number typed -> its index, or -1 */
static int choose(const char *want)
{
    char line[64];
    if (want) {
        for (int k = 0; k < NPACKS; k++)
            if (!strcmp(want, info[k].id))
                return k;
        printf("There's no build called %s here. These are the ones I carry:\n", want);
        list();
        return -1;
    }
    if (NPACKS == 1)
        return 0;
    printf("I can make these builds:\n");
    list();
    for (;;) {
        printf("Which one? Type its number (1 to %d) and press Return:\n", NPACKS);
        fflush(stdout);
        if (!fgets(line, sizeof line, stdin))
            return -1;
        int k = atoi(line);
        if (k >= 1 && k <= NPACKS)
            return k - 1;
        if (!interactive)
            return -1;
    }
}

int main(int argc, char **argv)
{
    const char *want = NULL, *arg = NULL;
    for (int k = 0; k < NPACKS; k++)
        if (dn2patch_info(packs[k], pack_len[k], &info[k])) {
            printf("This copy of digiwerk-patch is damaged. Download it again.\n");
            return 1;
        }
    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--list")) {
            list();
            return 0;
        } else if (!strcmp(argv[i], "--pack") && i + 1 < argc)
            want = argv[++i];
        else
            arg = argv[i];
    }
    interactive = isatty(fileno(stdin));
    if (NPACKS == 1)
        printf("digiwerk-patch makes %s.syx, Digiwerk's custom OS for the Digitone II, from your copy\n", info[0].id);
    else
        printf("digiwerk-patch makes Digiwerk's custom OS for the Digitone II from your copy\n");
    printf("of Elektron's OS 1.12 file (Digitone_II_OS1.12_dist.zip, or the .syx inside it).\n"
           "It only writes a new file; it sends nothing to the Digitone.\n\n");
    int k = choose(want);
    if (k < 0)
        return 1;
    if (NPACKS > 1)
        printf("\nMaking %s (%s).\n\n", info[k].id, info[k].title);
    char path[4096];
    if (arg) {
        snprintf(path, sizeof path, "%s", arg);
        return run(path, k) ? 1 : 0;
    }
    for (;;) {
        printf("Drag Digitone_II_OS1.12_dist.zip (or the .syx inside it) onto this window, then press Return:\n");
        fflush(stdout);
        if (!fgets(path, sizeof path, stdin))
            return 1;
        unshell(path, sizeof path);
        if (!path[0])
            continue;
        int r = run(path, k);
        if (r == 0 || r == 2 || !interactive)
            return r ? 1 : 0;
        printf("\nTry again, or press Control-C to stop.\n\n");
    }
}
